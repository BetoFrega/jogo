// Regenerates migrations/0001_auth.sql from the Better Auth options in src/auth.ts.
// Usage: npm run gen:auth-sql   (rerun after upgrading better-auth or changing plugins,
// then turn any diff into a NEW migration file rather than editing an applied one).
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.ts";

const options = authOptions({
  database: new DatabaseSync(":memory:"),
  baseURL: "http://localhost",
  secret: "x".repeat(32),
  turnstileSecretKey: "unused",
  google: { clientId: "unused", clientSecret: "unused" },
  sendMagicLink: async () => {},
});
const { compileMigrations } = await getMigrations(options);
const sql = (await compileMigrations()).trim();
const out = "migrations/0001_auth.sql";
writeFileSync(out, `-- Generated by scripts/gen-auth-sql.ts (better-auth). Do not edit by hand.\n${sql}\n`);
console.log(`wrote ${out}`);
